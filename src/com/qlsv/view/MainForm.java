private void showPanel(String tenForm) {

    pnlBody.removeAll();

    switch (tenForm) {

        case "KHOA": {
            KhoaForm form = new KhoaForm();
            pnlBody.add(form.getPanel(), BorderLayout.CENTER);
            break;
        }

        case "NGANH": {
            NganhForm form = new NganhForm();
            pnlBody.add(form, BorderLayout.CENTER);
            break;
        }

        case "LOP": {
            LopForm form = new LopForm();
            pnlBody.add(form, BorderLayout.CENTER);
            break;
        }

        case "SINHVIEN": {
            SinhVienForm form = new SinhVienForm();
            pnlBody.add(form, BorderLayout.CENTER);
            break;
        }

        case "MONHOC": {
            MonHocForm form = new MonHocForm();
            pnlBody.add(form, BorderLayout.CENTER);
            break;
        }

        case "DIEM": {
            DiemForm form = new DiemForm();
            pnlBody.add(form, BorderLayout.CENTER);
            break;
        }

        default: {
            JLabel lbl = new JLabel(
                "CHƯƠNG TRÌNH QUẢN LÝ SINH VIÊN",
                SwingConstants.CENTER
            );

            lbl.setFont(new Font("Arial", Font.BOLD, 24));
            lbl.setForeground(new Color(31, 45, 61));

            pnlBody.add(lbl, BorderLayout.CENTER);
            break;
        }
    }

    pnlBody.revalidate();
    pnlBody.repaint();
}


